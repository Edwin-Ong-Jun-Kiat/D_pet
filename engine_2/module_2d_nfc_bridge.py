# ── Request / Response models ──────────────────────────────────────────────────

class NfcTapRequest(BaseModel):
    pet_id: str                         # UUID written to the NFC tag
    owner_wallet: str | None = None     # Optional: used when decrypting IPFS payload


class NfcTapResponse(BaseModel):
    pet_id:     str
    phase:      str
    traits:     dict
    reply:      str                     # Greeting generated by Module 1C
    mint_address: str | None
    ipfs_uri:   str | None


class PairTagRequest(BaseModel):
    pet_id:        str
    nfc_tag_uuid:  str    # UUID written to the physical NFC chip


# ── Core business logic (callable without HTTP) ───────────────────────────────

def load_pet_from_nfc_tap(pet_id: str) -> dict:
    """
    Given a pet_id (read from NFC tag), return the pet's full state and
    generate a greeting via Module 1C.

    This is the function the HTTP endpoint calls — and also what the test
    calls directly to simulate a tap.

    Steps:
      1. Validate pet_id exists in Firebase.
      2. Load personality traits and phase.
      3. (Optional) Fetch and decrypt IPFS payload for richer context.
      4. Generate a welcome-back greeting via Claude.
      5. Return consolidated response dict.
    """
    pet = state_machine.get_pet(pet_id)
    if pet is None:
        raise ValueError(f"Pet {pet_id} not found. Is this tag paired?")

    traits = pet.get("traits", {})
    phase  = pet.get("phase", config.PHASES[0])

    logger.info("NFC tap: loading pet %s (phase=%s)", pet_id, phase)

    # Generate a warm greeting using the personality core
    greeting_prompt = (
        "Your owner just tapped your NFC chip to wake you up. "
        "Say a brief, enthusiastic, in-character hello — 1-2 sentences."
    )

    try:
        chat_result = personality.chat(pet_id, greeting_prompt)
        reply = chat_result["reply"]
        updated_traits = chat_result["traits"]
    except Exception as exc:
        logger.warning("Greeting generation failed: %s. Using fallback.", exc)
        reply = f"Hello! I'm your D-pet, currently in the {phase} phase!"
        updated_traits = traits

    return {
        "pet_id":       pet_id,
        "phase":        phase,
        "traits":       updated_traits,
        "reply":        reply,
        "mint_address": pet.get("mint_address"),
        "ipfs_uri":     pet.get("ipfs_uri"),
    }


def pair_nfc_tag(pet_id: str, nfc_tag_uuid: str) -> dict:
    """
    Associate a physical NFC tag UUID with a pet in Firebase.

    Called once during assembly: write a UUID to the NTAG215 chip,
    then call this function with that UUID and the pet's Firebase ID.
    """
    pet = state_machine.get_pet(pet_id)
    if pet is None:
        raise ValueError(f"Pet {pet_id} not found.")

    state_machine.update_pet(pet_id, {"nfc_tag_id": nfc_tag_uuid})
    logger.info("NFC tag %s paired to pet %s", nfc_tag_uuid, pet_id)

    return {"pet_id": pet_id, "nfc_tag_id": nfc_tag_uuid, "status": "paired"}


def lookup_pet_by_nfc_tag(nfc_tag_uuid: str) -> str | None:
    """
    Reverse-lookup: given a tag UUID, find the associated pet_id.
    Useful if the NFC tag stores only the tag UUID (not the pet_id directly).

    Returns pet_id string or None if not found.
    """
    db = get_db()
    pets_raw = db.reference("pets").get()
    if not pets_raw:
        return None

    for pid, pdata in pets_raw.items():
        if isinstance(pdata, dict) and pdata.get("nfc_tag_id") == nfc_tag_uuid:
            return pid

    return None


# ── FastAPI endpoints ──────────────────────────────────────────────────────────

@app.post("/nfc/tap", response_model=NfcTapResponse)
async def nfc_tap(request: NfcTapRequest):
    """
    Called by the mobile app immediately after it reads an NFC tag.

    The mobile app reads the pet_id from the tag and POSTs it here.
    This endpoint does all the heavy lifting (Firebase, Solana, IPFS, Claude)
    and returns the pet's personality for the app to display.

    For testing without a phone, call this endpoint directly:
        curl -X POST http://localhost:8000/nfc/tap \\
             -H "Content-Type: application/json" \\
             -d '{"pet_id": "<your-pet-uuid>"}'
    """
    try:
        result = load_pet_from_nfc_tap(request.pet_id)
        return NfcTapResponse(**result)
    except ValueError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
    except Exception as exc:
        logger.exception("NFC tap error for pet %s", request.pet_id)
        raise HTTPException(status_code=500, detail=str(exc))


@app.post("/nfc/pair")
async def pair_tag(request: PairTagRequest):
    """
    Pair a physical NFC tag UUID to a pet. Called once during assembly.
    """
    try:
        return pair_nfc_tag(request.pet_id, request.nfc_tag_uuid)
    except ValueError as exc:
        raise HTTPException(status_code=404, detail=str(exc))


@app.get("/nfc/lookup/{nfc_tag_uuid}")
async def lookup_by_tag(nfc_tag_uuid: str):
    """
    Resolve a tag UUID to a pet_id. Useful for debugging hardware.
    """
    pet_id = lookup_pet_by_nfc_tag(nfc_tag_uuid)
    if pet_id is None:
        raise HTTPException(status_code=404, detail=f"No pet found for tag {nfc_tag_uuid}")
    return {"nfc_tag_uuid": nfc_tag_uuid, "pet_id": pet_id}


@app.get("/health")
async def health():
    return {"status": "ok", "service": "dpet-nfc-bridge"}


# ── Simulation helper (used by tests) ─────────────────────────────────────────

def simulate_nfc_tap(pet_id: str) -> dict:
    """
    Simulate a physical NFC tap entirely in Python.

    Calls load_pet_from_nfc_tap() directly — bypassing HTTP — so the test
    exercises every line of real business logic without needing a phone or
    an HTTP server running.

    This is how module_2d is integration-tested:
        result = simulate_nfc_tap(pet_id)
        assert result["phase"] == "Egg"
        assert "reply" in result

    The only difference from a real tap: no bytes were read from a plastic
    chip. Every database, blockchain, and AI call is real.
    """
    logger.info("[SIMULATED NFC TAP] pet_id=%s", pet_id)
    return load_pet_from_nfc_tap(pet_id)


